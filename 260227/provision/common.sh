#!/usr/bin/env bash

# =========================================================

# =========================================================

set -euo pipefail

# =========================================================
# LOGGING
# =========================================================

log() {
    echo "[INFO] $1"
}

warn() {
    echo "[WARN] $1"
}

error() {
    echo "[ERROR] $1"
}

# =========================================================
# CHECK COMMAND EXISTS
# =========================================================

command_exists() {
    command -v "$1" &> /dev/null
}